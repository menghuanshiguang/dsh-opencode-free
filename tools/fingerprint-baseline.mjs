// The fingerprint baseline: what the lane sends, with the two per-run values
// normalised out so the number can be pinned in a lock file.
//
// The `<env>` block carries `process.cwd()` and `Today's date`, so the raw
// system-prompt hash changes with the runner's checkout path and with the day —
// pinning it as an assertion would fail the next morning, and pinning the byte
// count would fail on any runner whose path is longer than the one it was
// measured on. This tool replaces those two values with fixed placeholders
// before hashing, and leaves every other byte alone (the platform word and the
// rendered `shell` description stay in, because those are exactly what the
// upstream compares).
//
//   node tools/fingerprint-baseline.mjs [model]            # print
//   node tools/fingerprint-baseline.mjs [model] --write    # print + write docs/fingerprint-baseline.json
//   node tools/fingerprint-baseline.mjs [model] --assert   # compare with the lock, exit 1 on drift
//
// The lock is generated once on the runner and committed after a human confirms
// it (same rule as the asset blob-shas): CI never certifies its own expectation.
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { assetDir, load } from './upstream.mjs'

const { applyFingerprint, endpointFor } = await load('src/upstream.js')
const { CLIENT_UA, V2_CLIENT_VERSION } = await load('src/o2a/version.js')

const args = process.argv.slice(2)
const flags = args.filter(arg => arg.startsWith('--'))
const model = args.find(arg => !arg.startsWith('--')) ?? 'nemotron-3.5-lightning-free'
const lockPath = fileURLToPath(new URL('../docs/fingerprint-baseline.json', import.meta.url))

const sha = value => createHash('sha256').update(value).digest('hex')
const canon = value => {
  if (Array.isArray(value)) return `[${value.map(canon).join(',')}]`
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canon(value[key])}`).join(',')}}`
  }
  return JSON.stringify(value ?? null)
}

const body = {
  model,
  messages: [{ role: 'user', content: 'Do not use tools. Reply with exactly: PONG' }],
  stream: true,
  stream_options: { include_usage: true },
  max_completion_tokens: 128,
}
applyFingerprint(body, false)

const tools = Array.isArray(body.tools) ? body.tools : []
const systemMessage = (body.messages ?? []).find(message => message?.role === 'system' || message?.role === 'developer')
const rawPrompt = typeof systemMessage?.content === 'string' ? systemMessage.content : ''

// Normalise only the two values a runner controls. Everything else stays.
const normalised = rawPrompt
  .replace(/(Working directory: ).*(\n)/, '$1<workdir>$2')
  .replace(/(Workspace root folder: ).*(\n)/, '$1<workdir>$2')
  .replace(/(Today's date: ).*(\n)/, '$1<date>$2')

const shellTool = tools.find(tool => tool?.function?.name === 'shell')?.function
const shellPrefix = /Commands run on .*? using .*?\./.exec(shellTool?.description ?? '')?.[0] ?? ''

const baseline = {
  note: 'Generated by tools/fingerprint-baseline.mjs on ubuntu-latest; commit only after human confirmation.',
  model,
  platform: process.platform,
  clientVersion: V2_CLIENT_VERSION,
  userAgent: CLIENT_UA,
  endpoint: endpointFor(model),
  bodyKeys: Object.keys(body).sort(),
  toolCount: tools.length,
  toolNames: tools.map(tool => tool?.function?.name),
  toolsSha256: sha(JSON.stringify(tools)),
  normalisedSystemPrompt: { bytes: Buffer.byteLength(normalised), sha256: sha(normalised) },
  shellDescriptionPrefix: shellPrefix,
}

const printed = JSON.stringify(baseline, null, 2)
console.log(printed)

if (flags.includes('--write')) {
  writeFileSync(lockPath, `${printed}\n`)
  console.log(`\nwrote ${lockPath}`)
}

if (flags.includes('--assert')) {
  if (!existsSync(lockPath)) {
    console.error(`\nBASELINE: no lock at ${lockPath} — this run is NOT evidence (nothing to compare against)`)
    process.exit(2)
  }
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
  const failures = []
  for (const key of Object.keys(lock)) {
    if (key === 'note') continue
    const want = canon(lock[key])
    const got = canon(baseline[key])
    if (want !== got) failures.push(`${key}: lock ${want} != run ${got}`)
  }
  if (failures.length) {
    console.error(`\nBASELINE: FAIL (${failures.length})`)
    for (const failure of failures) console.error(`  - ${failure}`)
    process.exit(1)
  }
  console.log(`\nBASELINE: PASS (matches ${lockPath})`)
}
